export const CITY_OPTIONS = Object.keys(GERMAN_CITIES)
  .sort()
  .map((city) => ({ value: city, label: city }));

export function getDistrictOptions(city: string) {
  return (GERMAN_CITIES[city] ?? []).map((d) => ({ value: d.name, label: d.name }));
}

export function getStadtteilOptions(city: string, district: string) {
  const d = (GERMAN_CITIES[city] ?? []).find((d) => d.name === district);
  return (d?.stadtteile ?? []).map((s) => ({ value: s, label: s }));
}
